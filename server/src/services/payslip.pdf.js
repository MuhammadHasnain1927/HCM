import PDFDocument from 'pdfkit';

const BRAND = '#0f766e';
const MUTED = '#64748b';
const INK = '#0f172a';
const RULE = '#e2e8f0';

const money = (n, currency) =>
  `${currency} ${Number(n ?? 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const monthLabel = (month) => {
  const [y, m] = month.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, 1)).toLocaleDateString('en-GB', { month: 'long', year: 'numeric', timeZone: 'UTC' });
};

/** Streams a one-page payslip PDF to `res`. */
export function writePayslipPdf(res, payslip, { companyName, currency = 'PKR' }) {
  const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: `Payslip ${payslip.month} - ${payslip.employeeName}`, Author: companyName } });
  doc.pipe(res);
  const left = 48;
  const width = doc.page.width - 96;

  // Header
  doc.rect(0, 0, doc.page.width, 96).fill(BRAND);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(20).text(companyName, left, 30, { width: width * 0.6 });
  doc.font('Helvetica').fontSize(11).text('Salary slip', left, 58);
  doc.font('Helvetica-Bold').fontSize(14).text(monthLabel(payslip.month), left, 34, { width, align: 'right' });
  doc.font('Helvetica').fontSize(9).text(payslip.status === 'finalized' ? 'Finalized' : 'DRAFT - not final', left, 56, { width, align: 'right' });

  // Employee block
  let y = 120;
  const info = [
    ['Employee', payslip.employeeName],
    ['Employee code', payslip.employeeCode],
    ['Department', payslip.departmentName || '-'],
    ['Designation', payslip.designationTitle || '-'],
  ];
  doc.fillColor(INK);
  info.forEach(([label, value], i) => {
    const col = i % 2 === 0 ? left : left + width / 2;
    const row = y + Math.floor(i / 2) * 34;
    doc.font('Helvetica').fontSize(8).fillColor(MUTED).text(label.toUpperCase(), col, row);
    doc.font('Helvetica-Bold').fontSize(11).fillColor(INK).text(String(value ?? '-'), col, row + 11, { width: width / 2 - 12 });
  });
  y += 84;

  const sectionTitle = (title) => {
    doc.moveTo(left, y).lineTo(left + width, y).strokeColor(RULE).lineWidth(1).stroke();
    y += 10;
    doc.font('Helvetica-Bold').fontSize(10).fillColor(BRAND).text(title.toUpperCase(), left, y);
    y += 18;
  };
  const line = (label, value, { bold = false, color = INK } = {}) => {
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10).fillColor(MUTED).text(label, left, y, { width: width * 0.6 });
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10).fillColor(color).text(value, left, y, { width, align: 'right' });
    y += 18;
  };

  sectionTitle('Earnings');
  line('Basic salary', money(payslip.basic, currency));
  line('House rent allowance (40%)', money(payslip.hra, currency));
  line('Medical allowance (10%)', money(payslip.medical, currency));
  line('Gross salary', money(payslip.gross, currency), { bold: true });
  if (payslip.prorated) line(`Earned for ${payslip.employedDays} of ${payslip.workingDays} working days`, money(payslip.earned, currency));
  y += 6;

  sectionTitle('Attendance');
  line('Working days in month', String(payslip.workingDays));
  line('Absent days', String(payslip.absentDays));
  line('Unpaid leave days', String(payslip.unpaidLeaveDays));
  line('Half days (x 0.5)', String(payslip.halfDays));
  if (payslip.latePenaltyDays) line(`Late penalty (${payslip.lateDays} late days)`, String(payslip.latePenaltyDays));
  line('Per-day rate', money(payslip.perDay, currency));
  y += 6;

  sectionTitle('Deductions');
  line(`Attendance deductions (${payslip.deductionDays} day${payslip.deductionDays === 1 ? '' : 's'})`, money(payslip.deductions, currency));
  line('Income tax', money(payslip.tax, currency));
  y += 10;

  // Net pay box
  doc.roundedRect(left, y, width, 52, 6).fill('#f0fdfa');
  doc.font('Helvetica').fontSize(10).fillColor(MUTED).text('NET PAY', left + 16, y + 12);
  doc.font('Helvetica-Bold').fontSize(18).fillColor(BRAND).text(money(payslip.net, currency), left, y + 16, { width: width - 16, align: 'right' });
  y += 72;

  doc.font('Helvetica').fontSize(8).fillColor(MUTED).text(
    'Gross = 1.5 x basic (HRA 40%, medical 10%). Per day = gross / working days. Deductions = per day x (absent + unpaid leave + 0.5 x half days). ' +
      'Tax uses the yearly slab on gross x 12, shown per month. Generated by HCM Lite.',
    left,
    y,
    { width },
  );
  doc.end();
}
